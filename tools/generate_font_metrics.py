#!/usr/bin/env python3
"""Generate metric/encoding tables from licensed Adobe data, without font outlines."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/'assets/font-metrics'
FACES=['Courier','Courier-Bold','Courier-Oblique','Courier-BoldOblique','Helvetica','Helvetica-Bold','Helvetica-Oblique','Helvetica-BoldOblique','Times-Roman','Times-Bold','Times-Italic','Times-BoldItalic','Symbol','ZapfDingbats']

def generate():
    unicode_map={}
    for filename in ['glyphlist.txt','zapfdingbats.txt']:
        for line in (DATA/filename).read_text().splitlines():
            if not line or line.startswith('#'): continue
            name,codes=line.split(';')
            if ' ' not in codes: unicode_map[name]=int(codes,16)
    fonts=[]; encodings=[]; ascents=[]; descents=[]; copyrights=set()
    for face in FACES:
        glyphs={}; encoding={}; ascender=800; descender=-200
        for line in (DATA/(face+'.afm')).read_text().splitlines():
            if line.startswith('Comment Copyright'): copyrights.add(line.removeprefix('Comment '))
            if line.startswith('Ascender '): ascender=int(line.split()[1])
            if line.startswith('Descender '): descender=int(line.split()[1])
            if not line.startswith('C '): continue
            parts={item.strip().split()[0]:item.strip().split()[1:] for item in line.split(';') if item.strip()}
            name=parts['N'][0]; code=int(parts['C'][0])
            glyphs[name]=(int(parts['WX'][0]),tuple(map(int,parts['B'])))
            if code>=0: encoding[code]=name
        fonts.append(glyphs); encodings.append(encoding); ascents.append(ascender); descents.append(descender)
    names=['.notdef']+sorted(set().union(*fonts))
    ids={name:i for i,name in enumerate(names)}
    # Prefer Adobe's glyph names for Unicode, including compatibility ligatures.
    by_unicode={unicode_map[n]:n for n in names if n in unicode_map and any(n in f for f in fonts[:12])}
    win={}; mac={}
    for code in range(32,256):
        for codec,result in [('cp1252',win),('mac_roman',mac)]:
            try: point=ord(bytes([code]).decode(codec))
            except UnicodeDecodeError: continue
            if point in by_unicode: result[code]=by_unicode[point]
    for code in [127,129,141,143,144,157]: win[code]='bullet'
    win[160]='space'; win[173]='hyphen'
    # PDF MacRomanEncoding omits the Apple logo and uses space at 0xCA.
    for code in [173,178,179,182,183,195,198,215,240]: mac.pop(code,None)
    mac[202]='space'; mac[219]='currency'  # PDF 1.7 Appendix D.1, not modern Mac OS Euro.
    out=['// Generated by tools/generate_font_metrics.py. Modified representation of Adobe data.',
         '// Original notices and redistribution terms: assets/font-metrics/NOTICE.',
         'pub const Face = enum(u32) { courier, courier_bold, courier_oblique, courier_bold_oblique, helvetica, helvetica_bold, helvetica_oblique, helvetica_bold_oblique, times_roman, times_bold, times_italic, times_bold_italic, symbol, zapf_dingbats };',
         'pub const names = [_][]const u8{'+','.join(json.dumps(n) for n in FACES)+'};',
         'pub const ascent = [_]i16{'+','.join(map(str,ascents))+'};',
         'pub const descent = [_]i16{'+','.join(map(str,descents))+'};',
         'pub const Metric = struct { width: i16 = -1, bounds: [4]i16 = .{0,0,0,0} };',
         'pub const Glyph = struct { name: []const u8, unicode: u21, metrics: [14]Metric };',
         'pub const glyphs = [_]Glyph{']
    for name in names:
        metrics=[]
        for font in fonts:
            if name not in font: metrics.append('.{}'); continue
            width,box=font[name]; metrics.append('.{.width='+str(width)+',.bounds=.{'+','.join(map(str,box))+'}}')
        out.append('.{.name='+json.dumps(name)+',.unicode='+str(unicode_map.get(name,0))+',.metrics=.{'+','.join(metrics)+'}},')
    out.append('};')
    for name,encoding in [('standard',encodings[0]),('win_ansi',win),('mac_roman',mac),('symbol_encoding',encodings[12]),('dingbats_encoding',encodings[13])]:
        out.append('pub const '+name+' = [256]u16{'+','.join(str(ids.get(encoding.get(code,''),0)) for code in range(256))+'};')
    (ROOT/'src/font_metrics.zig').write_text('\n'.join(out)+'\n')
    license_header=(DATA/'glyphlist.txt').read_text().split('# Name:')[0]
    (DATA/'NOTICE').write_text('Adobe font metric and glyph mapping data\n\n'+ '\n'.join(sorted(copyrights))+'\n\n'+(DATA/'AFM-LICENSE').read_text()+'\n\n'+license_header+'\nGenerated tables change the representation only. See SOURCES.md for provenance and checksums.\n')
    print(f'{len(names)} glyphs; {len(FACES)} faces')

if __name__=='__main__': generate()
